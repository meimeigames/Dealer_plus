// Builds the static site into ./dist for GitHub Pages.
// - copies the app files
// - writes js/config.js from env (SUPABASE_URL / SUPABASE_ANON_KEY) when present
// - stamps a build id into sw.js / index.html for cache busting
import { cpSync, mkdirSync, rmSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';

const out = 'dist';
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const p of ['index.html', 'manifest.webmanifest', 'sw.js', '.nojekyll', 'css', 'js', 'icons', 'assets/sheets', 'assets/photo', 'assets/photos', 'assets/walls', 'assets/homes']) {
  if (existsSync(p)) cpSync(p, `${out}/${p}`, { recursive: true }); // assets/src (original sheets) stays out of the site
}

let build = process.env.GITHUB_SHA ? process.env.GITHUB_SHA.slice(0, 8) : '';
if (!build) { try { build = execSync('git rev-parse --short HEAD').toString().trim(); } catch { build = String(Date.now()); } }
build += '-' + Date.now().toString(36);

// repository secrets win; otherwise the public server committed in js/config.js (the anon key is public by design)
const committed = readFileSync('js/config.js', 'utf8');
const pick = (name) => (committed.match(new RegExp(`${name}:\\s*'([^']*)'`)) || [])[1] || '';
const url = (process.env.SUPABASE_URL || pick('supabaseUrl')).trim().replace(/\/+$/, '');
const key = (process.env.SUPABASE_ANON_KEY || pick('supabaseKey')).trim();
writeFileSync(`${out}/js/config.js`,
  `// generated by scripts/build.mjs\nwindow.GR_CONFIG = ${JSON.stringify({ supabaseUrl: url, supabaseKey: key, build })};\n`);

// every module import carries the build id: after an update the phone loads one consistent set of files instead of
// mixing fresh modules with ones still in the HTTP cache (GitHub Pages caches for 10 minutes)
import { readdirSync, statSync } from 'node:fs';
const IMPORT_RE = /(\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)(['"])(\.{1,2}\/[^'"?]+\.js)\2/g;
const walk = (d) => readdirSync(d).flatMap((n) => { const p = `${d}/${n}`; return statSync(p).isDirectory() ? walk(p) : p.endsWith('.js') ? [p] : []; });
let stamped = 0;
for (const p of walk(`${out}/js`)) {
  const src = readFileSync(p, 'utf8');
  const res = src.replace(IMPORT_RE, (m, a, q, path) => { stamped++; return `${a}${q}${path}?v=${build}${q}`; });
  if (res !== src) writeFileSync(p, res);
}
console.log(`stamped ${stamped} module imports`);
for (const f of ['sw.js', 'index.html']) {
  const p = `${out}/${f}`;
  writeFileSync(p, readFileSync(p, 'utf8').replaceAll('__BUILD__', build));
}
console.log(`built ${out}/ (build ${build}, online: ${url ? 'yes' : 'no'})`);
